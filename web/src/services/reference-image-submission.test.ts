import axios from "axios";
import { afterEach, beforeEach, expect, test, vi } from "vitest";
import { createModelChannel, defaultConfig } from "@/stores/use-config-store";
import { useUserStore } from "@/stores/use-user-store";
import { resetManagedCatalogForTests } from "@/lib/desktop/managed-catalog-cache";
import { submitAdapterRemoteMediaTask } from "./api/remote-media-task";
import { generateResolvedMedia } from "./api/media-dispatcher";
